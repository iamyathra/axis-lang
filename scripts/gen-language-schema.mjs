#!/usr/bin/env node
// Generates docs/ai/schema.json: the closed-vocabulary subset of AXIS that
// already exists as real allow-list constants in the source (not a
// hand-maintained duplicate of them) - named colors, easing curves, camera
// controls, material fields, responsive breakpoints, interaction events,
// and diagnostic codes. Run after changing any of the constants below.
//
//   node scripts/gen-language-schema.mjs
//
// This is deliberately NOT a full grammar/property schema. AXIS's per-
// element-type property validation (interpreter.js's applyProperty
// methods) is a series of inline switch statements, not a single data
// structure - extracting a complete, accurate schema from that would mean
// either re-deriving it by hand (a second, driftable source of truth) or a
// real refactor of interpreter.js (out of scope for this milestone). The
// values below are different: each one already *is* a single Set/array
// constant in the source, exported for exactly this purpose - generating
// this file duplicates nothing.
import { writeFileSync } from "node:fs";
import nodePath from "node:path";
import { fileURLToPath } from "node:url";
import { CAMERA_CONTROLS, MATERIAL_FIELDS, RESPONSIVE_BREAKPOINTS, EVENT_NAMES } from "../src/interpreter.js";
import { NAMED_COLORS, EASING_NAMES } from "../src/globals.js";
import { CODE_CATALOG, DIAGNOSTIC_SCHEMA_VERSION } from "../src/diagnostics.js";
import { createRequire } from "node:module";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const { version: axisVersion } = createRequire(import.meta.url)("../package.json");

const schema = {
  $comment:
    "Generated by scripts/gen-language-schema.mjs. Closed-vocabulary AXIS values only - see docs/language.md for the full grammar this doesn't attempt to replace.",
  axisVersion,
  diagnosticSchemaVersion: DIAGNOSTIC_SCHEMA_VERSION,
  // Every top-level item AXIS's parser accepts (parser.js's own top-level
  // dispatch) - kept here as a literal list, not extracted, since that
  // dispatch is an if/else chain, not a data table; keep this in sync with
  // parser.js if that list changes.
  topLevelKeywords: ["scene", "page", "fn", "async fn", "component", "let", "const", "state", "import", "export", "route", "redirect"],
  namedColors: [...NAMED_COLORS],
  easingNames: [...EASING_NAMES],
  cameraControls: [...CAMERA_CONTROLS],
  materialFields: [...MATERIAL_FIELDS],
  responsiveBreakpoints: [...RESPONSIVE_BREAKPOINTS],
  interactionEvents: [...EVENT_NAMES],
  diagnosticCodes: Object.keys(CODE_CATALOG).sort(),
};

const OUT = nodePath.join(ROOT, "docs", "ai", "schema.json");
writeFileSync(OUT, JSON.stringify(schema, null, 2) + "\n");
console.log(`wrote ${nodePath.relative(ROOT, OUT)}`);
