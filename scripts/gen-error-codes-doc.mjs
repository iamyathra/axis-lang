#!/usr/bin/env node
// Regenerates docs/ai/ERROR_CODES.md from src/diagnostics.js's own
// CODE_CATALOG - the one place all of AXIS's diagnostic codes and their
// descriptions are defined. Run this after adding/changing a code so the
// doc never drifts out of sync with the code (tests/diagnostics.test.js
// separately guards that CODE_CATALOG itself stays complete).
//
//   node scripts/gen-error-codes-doc.mjs

import { writeFileSync } from "node:fs";
import nodePath from "node:path";
import { fileURLToPath } from "node:url";
import { CODE_CATALOG, DIAGNOSTIC_SCHEMA_VERSION } from "../src/diagnostics.js";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT = nodePath.join(ROOT, "docs", "ai", "ERROR_CODES.md");

const codes = Object.keys(CODE_CATALOG).sort();

const rows = codes.map((code) => `| \`${code}\` | ${CODE_CATALOG[code]} |`).join("\n");

const doc = `<!-- Generated by scripts/gen-error-codes-doc.mjs from src/diagnostics.js's CODE_CATALOG. Don't hand-edit - run the script instead. -->

# AXIS diagnostic codes (schema v${DIAGNOSTIC_SCHEMA_VERSION})

Every diagnostic \`axis check --json\` reports has a \`code\` field. This is the complete list AXIS can currently produce - see [VALIDATION.md](VALIDATION.md) for the full JSON contract these codes appear in.

A code ending in \`_ERROR\` (\`AXIS_PARSE_ERROR\`, \`AXIS_MODULE_ERROR\`, \`AXIS_RUNTIME_ERROR\`) is a **fallback**: AXIS threw a real error of that category, but it didn't match any of the more specific codes below - read \`message\` for the actual problem. Every other code is specific enough that its name alone tells you the shape of the fix, even without reading \`message\`.

${codes.length} codes total.

| Code | Meaning |
| --- | --- |
${rows}
`;

writeFileSync(OUT, doc);
console.log(`wrote ${nodePath.relative(ROOT, OUT)} (${codes.length} codes)`);
